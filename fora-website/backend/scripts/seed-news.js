async function loadStrapi() {
  const factory = require('@strapi/strapi');
  if (typeof factory.compileStrapi === 'function' && typeof factory.createStrapi === 'function') {
    const ctx = await factory.compileStrapi();
    return factory.createStrapi(ctx).load();
  }
  if (typeof factory.createStrapi === 'function') return factory.createStrapi().load();
  if (typeof factory === 'function') return factory().load();
  if (factory.default) return factory.default().load();
  throw new Error('Δεν βρέθηκε τρόπος εκκίνησης του Strapi.');
}

async function main() {
  const app = await loadStrapi();
  app.log.level = 'error';

  let created = 0;
  let updated = 0;

  for (const a of ARTICLES) {
    const data = {
      titlos: a.titlos,
      slug: a.slug,
      imerominia: a.imerominia,
      katigoria: a.katigoria,
      perilipsi: a.perilipsi,
      keimeno: a.keimeno,
      xronosAnagnosis: a.xronosAnagnosis || null,
      proveblimeno: !!a.proveblimeno,
    };

    const found = await app.documents('api::arthro.arthro').findMany({
      filters: { slug: a.slug },
      status: 'draft',
    });

    if (found && found.length) {
      await app.documents('api::arthro.arthro').update({
        documentId: found[0].documentId,
        data,
        status: 'published',
      });
      updated += 1;
      console.log(`• ενημερώθηκε: ${a.titlos}`);
    } else {
      await app.documents('api::arthro.arthro').create({ data, status: 'published' });
      created += 1;
      console.log(`• δημιουργήθηκε: ${a.titlos}`);
    }
  }

  console.log(`\nΈτοιμο. Νέα άρθρα: ${created}, ενημερωμένα: ${updated}, σύνολο: ${ARTICLES.length}.`);
  console.log('Οι φωτογραφίες ανεβαίνουν χειροκίνητα: κάθε άρθρο έχει στο τέλος');
  console.log('του κειμένου το permalink του post, από όπου κατεβάζετε την εικόνα.');

  await app.destroy();
  process.exit(0);
}

